CREATE TABLE IF NOT EXISTS solicitud_acceso (
 id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL,
 nombre_usuario VARCHAR(60) NOT NULL,
 correo VARCHAR(190) NOT NULL,
 telefono VARCHAR(25),
 nombre_comercial VARCHAR(120),
 hash_contrasena VARCHAR(255) NOT NULL,
 rol VARCHAR(20) NOT NULL CHECK(rol IN ('proveedor','administrador')),
 estado VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK(estado IN ('pendiente','aprobada','rechazada')),
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 revisada_en TIMESTAMPTZ,
 revisada_por BIGINT REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
 id_usuario_creado BIGINT REFERENCES usuario(id_usuario) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_solicitud_usuario_pendiente ON solicitud_acceso(nombre_usuario) WHERE estado='pendiente';
CREATE UNIQUE INDEX IF NOT EXISTS uq_solicitud_correo_pendiente ON solicitud_acceso(lower(correo)) WHERE estado='pendiente';
